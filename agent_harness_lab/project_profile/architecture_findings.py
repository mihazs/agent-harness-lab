"""Findings from recorded decisions and architectural patterns against the harness text (#1136).

A contradiction is a harness line that runs a tool an accepted record decided against (or the one a superseded record chose,
when an accepted record replaced it), or that cites a superseded record as current. A gap is a decision-record folder or a
detected pattern (workspace dependency edges, generated code, migrations) that no instruction file mentions. Whatever cannot be
settled stays silent: a record without a plain accepted or superseded status, a title that does not name exactly one tool,
accepted records that disagree, a group the repository's own lockfile or dependencies already settle (the toolchain findings
own that case), a negated or historical line. The check is lexical and does not judge whether agents touch the area.
"""
import re

from agent_harness_lab.project_profile import architecture, commands, findings, harness_text

_DECISIONS = re.compile(r'\badrs?\b|decision records?|architecture decisions?', re.I)
PATTERN_WORDS = dict(workspace_dependencies=frozenset('workspace workspaces monorepo'.split()),
                     generated_code=frozenset('generated autogenerated codegen'.split()),
                     migrations=frozenset('migration migrations'.split()))
_HISTORIC = re.compile(r'\b(?:supersed\w*|obsolete|replaced|historical|legacy|history|was|were)\b', re.I)


def _says(mentions, group):
    """{tool: [mentions]} of the group's tools that the root harness commands run."""
    found = {}
    for mention in mentions:
        if mention['scope'] != 'root': continue
        for name in {mention['command']['program'], commands.unwrapped(mention['command'])['program']} & set(architecture.GROUPS[group]):
            found.setdefault(name, []).append(mention)
    return found


def _settled(profile, group):
    names = {row['name'] for row in profile['technologies'] if row['kind'] in ('package_manager', 'test_runner')}
    return bool(names & set(architecture.GROUPS[group]))


def _wrong_tools(records):
    """(record, tool, kind) for each tool a decision rules out: the others of the group an accepted record chose (when the
    accepted records of the group agree), and the tool a superseded record chose when its accepted replacement chose another."""
    found, by_number = [], {(row['folder'], row['number']): row for row in records}
    for group, tools in architecture.GROUPS.items():
        accepted = [row for row in records if row['status'] == 'accepted' and architecture.group_of(row['tool']) == group]
        if len({row['tool'] for row in accepted}) == 1:
            found += [(accepted[0], tool, 'decision_contradicted') for tool in tools if tool != accepted[0]['tool']]
    for old in records:
        new = by_number.get((old['folder'], old['superseded_by']))
        if old['status'] == 'superseded' and new and new['status'] == 'accepted' and old['tool'] and new['tool'] and old['tool'] != new['tool'] \
                and architecture.group_of(old['tool']) == architecture.group_of(new['tool']):
            found.append((new, old['tool'], 'superseded_decision_stated'))
    return found


def _cited(entries, records):
    """{record path: [where]} of root harness lines that cite a superseded record by path or as `ADR-N`."""
    found = {}
    for entry in entries:
        if entry['scope'] not in ('root', 'nested'): continue
        for number, line in enumerate(entry['text'].splitlines(), 1):
            if _HISTORIC.search(line) or harness_text._NEGATION.search(line): continue
            for record in records:
                if record['status'] == 'superseded' and (record['path'] in line or re.search(rf'\badr[\s-]*0*{record["number"]}(?!\d)', line, re.I)):
                    found.setdefault(record['path'], []).append(dict(file=entry['path'], line=number))
    return found


def contradictions(profile, entries, mentions):
    records = (profile.get('architecture') or {}).get('decisions') or []
    found = []
    for record, tool, kind in _wrong_tools(records):
        group = architecture.group_of(tool)
        rows = _says(mentions, group).get(tool)
        if rows and not _settled(profile, group) and architecture.group_of(record['tool']) == group:
            found.append(findings.finding(kind, tool, group, dict(group=group, named=tool, decided=record['tool'], mentions=len(rows)),
                                          findings._where(rows), dict(record=record['path'])))
    found += [findings.finding('superseded_decision_stated', path, 'record', dict(mentions=len(rows)), rows) for path, rows in sorted(_cited(entries, records).items())]
    return found[:findings.MAX_PER_KIND * 2]


def gaps(profile, entries):
    arch, words = profile.get('architecture') or {}, findings._words(entries)
    text = '\n'.join(entry['text'] for entry in entries)
    accepted = [row for row in arch.get('decisions') or [] if row['status'] == 'accepted']
    found = []
    if accepted and not (_DECISIONS.search(text) or any(folder in text for folder in arch['decision_dirs'])):
        found.append(findings.finding('decision_records_unstated', 'decision_records', '', dict(accepted=len(accepted), records=len(arch['decisions']),
                     folders=len(arch['decision_dirs'])), [], dict(folders=arch['decision_dirs'])))
    work, migrations = arch.get('workspace') or {}, profile['layout']['migration_dirs']
    seen = dict(workspace_dependencies=(dict(packages=work['packages'], internal_edges=work['internal_edges']), []) if work.get('internal_edges') else None,
                generated_code=(dict(directories=len(arch['generated_dirs'])), arch['generated_dirs']) if arch.get('generated_dirs') else None,
                migrations=(dict(directories=len(migrations)), migrations) if migrations else None)
    for name, item in seen.items():
        if item and not words & PATTERN_WORDS[name] and not any(path in text for path in item[1]):
            found.append(findings.finding('pattern_not_stated', name, name, item[0], [], dict(pattern=name, paths=item[1][:findings.MAX_WHERE])))
    return found
